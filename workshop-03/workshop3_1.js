// Workshop 3.1: คำนวณผลรวมเลขคู่ และผลคูณเลขคี่
// เงื่อนไข: ใช้ for loop ตามที่โจทย์กำหนด

// ส่วนที่ 1: หาผลรวมเลขคู่ 2-50
let sumEven = 0;
for (let i = 2; i <= 50; i += 2) {
    sumEven += i;                     // บวกสะสมเลขคู่เข้าไปในตัวแปร
}

// ส่วนที่ 2: หาผลคูณเลขคี่ 1-10
let productOdd = 1;
for (let j = 1; j <= 10; j += 2) {
    productOdd *= j;                 // คูณสะสมเลขคี่เข้าไปในตัวแปร (1*3*5*7*9)
}

// แสดงผลลัพธ์ออกทาง console
console.log("ผลรวมเลขคู่ 2-50 = " + sumEven);
console.log("ผลคูณเลขคี่ 1-10 = " + productOdd);

